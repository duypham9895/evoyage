import { describe, it, expect, vi, beforeEach } from 'vitest';
import { NextRequest } from 'next/server';

// ── Mocks (external I/O only) ──

vi.mock('@/lib/rate-limit', () => ({
  checkRateLimit: vi.fn().mockResolvedValue({ allowed: true, remaining: 19, retryAfterSec: 0 }),
  getClientIp: vi.fn().mockReturnValue('203.0.113.42'),
}));

vi.mock('@/lib/prisma', () => ({
  prisma: {
    chargingStation: { findUnique: vi.fn() },
    vinFastStationDetail: { findFirst: vi.fn(), upsert: vi.fn() },
  },
}));

vi.mock('@/lib/vinfast/vinfast-client', () => ({
  fetchVinFastDetailWithProgress: vi.fn(),
}));

vi.mock('@/lib/vinfast/vinfast-entity-resolver', () => ({
  resolveEntityId: vi.fn(),
}));

// ── Imports (after mocks) ──

import { GET } from './route';
import { prisma } from '@/lib/prisma';
import { resolveEntityId } from '@/lib/vinfast/vinfast-entity-resolver';

const mockFindStation = vi.mocked(prisma.chargingStation.findUnique);
const mockResolveEntityId = vi.mocked(resolveEntityId);

// 25-char Prisma cuid (shape created by @default(cuid())).
const CUID_ID = 'clxabcdef0123456789abcde1';
// 17-char id as generated by scripts/crawl-vinfast-stations.ts:197
// (`c${Date.now().toString(36)}${Math.random().toString(36).slice(2, 10)}`).
// This exact id is a live ACTIVE VinFast station in prod (entityId 28896).
const CRAWLER_ID = 'cmolmt0xkii77gjoh';

function vinfastStation(id: string) {
  return {
    id,
    name: 'VinFast Test Station',
    address: '1 Test St',
    latitude: 10.77,
    longitude: 106.7,
    isVinFastOnly: true,
    ocmId: 'vinfast-store-1',
    storeId: 'store-1',
    connectorTypes: '["CCS2"]',
    chargingStatus: 'ACTIVE',
    parkingFee: false,
    accessType: 'Public',
    maxPowerKw: 60,
    portCount: 2,
  };
}

async function callRoute(id: string) {
  const req = new NextRequest(`http://localhost/api/stations/${id}/vinfast-detail`);
  const res = await GET(req, { params: Promise.resolve({ id }) });
  const body = await res.text();
  return { status: res.status, body };
}

describe('GET /api/stations/[id]/vinfast-detail — id validation', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockFindStation.mockImplementation((async (args: { where: { id: string } }) =>
      vinfastStation(args.where.id)) as never);
    // No entity mapping -> route serves basic DB detail (no scraping, no cache read).
    mockResolveEntityId.mockResolvedValue({ entityId: null } as never);
  });

  it('serves detail for a 25-char cuid station id', async () => {
    const { status, body } = await callRoute(CUID_ID);
    expect(status).toBe(200);
    expect(body).toContain('"stage":"done"');
  });

  it('rejects ids with characters outside [a-z0-9] as INVALID_ID', async () => {
    const { status, body } = await callRoute('../etc/passwd');
    expect(status).toBe(400);
    expect(body).toContain('INVALID_ID');
  });

  // BUG(p0-vinfast-detail-invalid-id): id regex {20,36} rejects the 17-char ids the VinFast crawler writes. Fixer: change it.fails -> it once fixed. See docs/bugs/2026-11-01-p0-vinfast-detail-invalid-id.md
  it.fails('serves detail for a 17-char crawler-generated VinFast station id', async () => {
    const { status, body } = await callRoute(CRAWLER_ID);
    expect(body).not.toContain('INVALID_ID');
    expect(status).toBe(200);
    expect(body).toContain('"stage":"done"');
  });
});
